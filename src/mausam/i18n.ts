/** Returns a translator for the active language, keyed by the English source string. */
export function makeT(lang: Lang) {
  return (en: string, _hi?: string): string => {
    if (!en || lang === "en") return en;
    const direct = dict[en]?.[lang];
    if (direct) return direct;

    const trimmed = en.trim();
    if (trimmed !== en && dict[trimmed]?.[lang]) return dict[trimmed]![lang];

    if (en === en.toUpperCase() && en.length > 1) {
      const titleCase = en.charAt(0).toUpperCase() + en.slice(1).toLowerCase();
      if (dict[titleCase]?.[lang]) return dict[titleCase]![lang];
    }

    return translateDynamicPattern(en, lang);
  };
}
